-- Provide one plain item-use macro for all supported conjured water and food.
local driver = CreateFrame("Frame")
local water = { 231778, 22018, 8079, 8078, 8077, 3772, 2136, 2288, 5350 }
local food = { 22895, 8076, 8075, 1487, 1114, 1113, 5349 }

local function ItemBody(items)
    local lines = {}
    for _, itemID in ipairs(items) do
        lines[#lines + 1] = "/use item:" .. itemID
    end
    return table.concat(lines, "\n")
end

local macroName = "Use Conjured All"
local body = ItemBody(water) .. "\n" .. ItemBody(food)
local chainedBody = "/click ForeverTweaksUseConjuredWater\n/click ForeverTweaksUseConjuredFood"
local created
local legacyBody = ItemBody({
    22018, 8079, 8078, 8077, 3772, 2136, 2288, 5350,
    22895, 8076, 8075, 1487, 1114, 1113, 5349,
})

local function Normalize(body)
    return body and body:gsub("\r\n", "\n"):gsub("\n+$", "")
end

-- Re-read indices after each edit or creation because macro names affect ordering.
local function FindMacro(name, expectedBody)
    local accountCount, characterCount = GetNumMacros()
    local base = Constants.MacroConsts.MAX_ACCOUNT_MACROS
    local found, matches
    matches = 0
    local function Inspect(index)
        local existingName, _, body = GetMacroInfo(index)
        if existingName == name then
            matches = matches + 1
            if not expectedBody or Normalize(body) == expectedBody then found = index end
        end
    end
    for index = 1, accountCount do Inspect(index) end
    for index = base + 1, base + characterCount do Inspect(index) end
    if matches == 1 then return found, matches end
    return nil, matches
end

-- Remove only the exact component macros generated by the previous implementation.
local function RemoveComponent(name, expectedBody)
    local index = FindMacro(name, expectedBody)
    if not index then return end
    local _, _, oldBody = GetMacroInfo(index)
    local character = index > Constants.MacroConsts.MAX_ACCOUNT_MACROS
    DeleteMacro(index)
    local _, matches = FindMacro(name)
    if matches ~= 0 then return end
    for slot, entry in pairs(ForeverTweaksQuickMenu or {}) do
        if type(entry) == "table" and entry.kind == "macro"
            and entry.name == name and entry.body == oldBody and entry.character == character then
            ForeverTweaksQuickMenu[slot] = nil
        end
    end
end

local function RewriteMacro(index)
    local oldName, _, oldBody = GetMacroInfo(index)
    local character = index > Constants.MacroConsts.MAX_ACCOUNT_MACROS
    local updated = EditMacro(index, macroName, nil, body)
    if not updated then return end
    local name, _, saved = GetMacroInfo(updated)
    if name ~= macroName or Normalize(saved) ~= body then return end
    for _, entry in pairs(ForeverTweaksQuickMenu or {}) do
        if type(entry) == "table" and entry.kind == "macro"
            and entry.name == oldName and entry.body == oldBody and entry.character == character then
            entry.name, entry.body = name, saved
        end
    end
end

local function Synchronize()
    if InCombatLockdown() or GetCursorInfo() or #body > 255 then return end
    RemoveComponent("Use Conjured Water", ItemBody(water))
    RemoveComponent("Use Conjured Food", ItemBody(food))
    local index, matches = FindMacro(macroName)
    if matches > 0 then
        if index then
            local _, _, existing = GetMacroInfo(index)
            if Normalize(existing) == chainedBody then RewriteMacro(index) end
        end
        return
    end
    local legacy = FindMacro("Food & Water", legacyBody)
    if legacy then
        RewriteMacro(legacy)
        return
    end
    local _, count = GetNumMacros()
    if not created and count < Constants.MacroConsts.MAX_CHARACTER_MACROS then
        created = CreateMacro(macroName, "INV_Misc_Food_10", body, true)
    end
end

local queued = false
driver:SetScript("OnEvent", function()
    if queued then return end
    queued = true
    C_Timer.After(0, function()
        queued = false
        Synchronize()
    end)
end)
driver:RegisterEvent("PLAYER_LOGIN")
driver:RegisterEvent("PLAYER_REGEN_ENABLED")
driver:RegisterEvent("CURSOR_CHANGED")
driver:RegisterEvent("UPDATE_MACROS")
